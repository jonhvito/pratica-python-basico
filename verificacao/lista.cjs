const assert = require("node:assert/strict");
const lista = require("../lista-avaliacao.js");
const progress = require("../progresso.js");
const storage = require("../armazenamento.js");
const tests = require("../lista-testes.js").entries;
const obrigatorios = "1 2a 2b 3a 4b 4c 6a 6b 6c 6d 7a 7b 7c 8a 8b 9a 10a 10c 11a 12a 12b 12c 13a 13c 14a 14b 15a 15b 15c 15d 16a 16b 16c 17a 18a 18b 18c 19a 19c 19d 20c 20d".split(" ");
assert.deepEqual(Object.keys(tests).sort(), obrigatorios.sort());
assert.equal(lista.itens.length, 20);
assert.deepEqual(lista.itens.map(item => item.numero), Array.from({ length: 20 }, (_, i) => i + 1));
assert.deepEqual(lista.itens.filter(item => item.semConsulta).map(item => item.numero), [1, 2, 6, 7, 8]);
assert.equal(lista.revisao.length, 11);
const letras = ["", "ab", "abc", "abc", "abc", "abcd", "abc", "abcd", "abcd", "abcd", "abc", "abcd", "abc", "abc", "abcd", "abc", "abcd", "abcd", "abcd", "abcde"];
lista.itens.forEach((item, index) => {
  assert.ok(item.paginas && item.dica && item.criterios && item.enunciado);
  for (const letra of letras[index]) assert.ok(item.enunciado.includes("(" + letra + ")"), `${item.numero}${letra}`);
});
for (const palavra of ["range(7, 7)", "range(9, 2, -3)"]) assert.ok(lista.itens[3].enunciado.includes(palavra));
assert.ok(lista.itens[4].enunciado.includes("xi True or False and False"));
assert.ok(lista.itens[19].enunciado.includes("vii resumo"));
const exercises = [{id: "antigo"}];
const old = {version: 4, drafts: {antigo: {code: "pass"}}, outraExtensao: {conteudo: 4}};
const extended = {...old, listaAvaliacao: {active: 2, drafts: {"1": {code: "def sinal(x):\n    return '+'", notes: "anotação", subitem: "1", extra: "preservado"}}, campoFuturo: 8}};
const checked = progress.validateBackup(extended, exercises).state;
assert.deepEqual(checked.listaAvaliacao, extended.listaAvaliacao);
const legacy = {...old, listaAvaliacao: {drafts: {"1": {code: "pass", campoFuturo: true}}, campoFuturo: 9}};
assert.deepEqual(progress.validateBackup(legacy, exercises).state.listaAvaliacao, legacy.listaAvaliacao);
assert.equal(Object.hasOwn(legacy.listaAvaliacao, "active"), false);
const legacySubitem = {...old, listaAvaliacao: {drafts: {"1": {subitem: {campoFuturo: 2}}}}};
assert.deepEqual(progress.validateBackup(legacySubitem, exercises).state.listaAvaliacao, legacySubitem.listaAvaliacao);
assert.throws(() => progress.validateBackup({...old, listaAvaliacao: {active: 1, drafts: {"1": {notes: 2}}}}, exercises));
const map = new Map([[storage.key, JSON.stringify(extended)]]);
const mem = {getItem: key => map.has(key) ? map.get(key) : null, setItem: (key, value) => map.set(key, value), removeItem: key => map.delete(key)};
const adapter = storage.create({storage: mem, exercises});
assert.equal(adapter.load().status, "ready");
assert.equal(adapter.save(checked).ok, true);
const exported = adapter.exportState(checked);
assert.deepEqual(exported.listaAvaliacao, extended.listaAvaliacao);
assert.deepEqual(exported.outraExtensao, old.outraExtensao);
assert.equal(adapter.replace(old).ok, true);
assert.equal(progress.validateBackup(old, exercises).state.listaAvaliacao, undefined);
console.log("OK: catálogo da lista, subitens, revisão e backup em memória.");
